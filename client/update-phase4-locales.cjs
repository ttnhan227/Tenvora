for (const [code, newEntries] of Object.entries(locales)) {
  const filePath = path.join(__dirname, 'src', 'locales', `${code}.ts`);
  let content = fs.readFileSync(filePath, 'utf8');

  // Find the closing brace of the export
  const lastBraceIdx = content.lastIndexOf('};');
  if (lastBraceIdx === -1) {
    console.error(`Could not find closing brace in ${filePath}`);
    continue;
  }

  // Format new lines
  const entriesStr = Object.entries(newEntries)
    .map(([key, val]) => `  ${JSON.stringify(key)}: ${JSON.stringify(val)},`)
    .join('\r\n');

  const before = content.slice(0, lastBraceIdx);
  const after = content.slice(lastBraceIdx);

  const updated = before + entriesStr + '\r\n' + after;
  fs.writeFileSync(filePath, updated, 'utf8');
  console.log(`Updated ${code}.ts with ${Object.keys(newEntries).length} keys.`);
}
