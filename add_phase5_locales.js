for (const [lang, dict] of Object.entries(locales)) {
  const filePath = path.join(__dirname, 'client/src/locales', `${lang}.ts`);
  let content = fs.readFileSync(filePath, 'utf8');
  const eol = content.includes('\r\n') ? '\r\n' : '\n';

  // Find closing "};"
  const closingIdx = content.lastIndexOf('};');
  if (closingIdx === -1) {
    console.error(`Closing not found in ${lang}.ts`);
    continue;
  }

  const entriesToAdd = [];
  for (const [k, v] of Object.entries(dict)) {
    if (!content.includes(`"${k}":`)) {
      entriesToAdd.push(`  "${k}": ${JSON.stringify(v)},`);
    }
  }

  if (entriesToAdd.length > 0) {
    const insertStr = entriesToAdd.join(eol) + eol;
    content = content.slice(0, closingIdx) + insertStr + content.slice(closingIdx);
    fs.writeFileSync(filePath, content, 'utf8');
    console.log(`Updated ${lang}.ts with ${entriesToAdd.length} keys`);
  } else {
    console.log(`${lang}.ts already up to date`);
  }
}
